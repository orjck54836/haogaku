/**
 * 基本文法介紹（初級）。
 *
 * ## 為什麼是手寫而不是產生的
 *
 * 文法和五十音一樣是**封閉的知識**——「は」和「が」的差別不會因為情境換了就不同，
 * 產生出來的版本每次用字不一樣反而讓人以為規則有兩套。
 * 而且這是初級的人最早會卡住的地方，錯一句的代價比生活主題高很多。
 * 所以走 `Unit[]` 手寫，和 `basics` 同一條路：離線能用、不吃 AI 額度、內容固定。
 *
 * ## 挑這些單元的理由
 *
 * 不做「文法大全」。收的標準是**看懂並說出一句日文最少需要什麼**：
 * 句尾（です・ます）、助詞、動詞的三個形、形容詞，再加上開口第一天就會用到的
 * 「有沒有、想不想、幾個、為什麼」。學完能拆解生活主題裡的句子就夠了，
 * 剩下的交給主題課在情境裡遇到。
 *
 * 進階文法（條件、被動使役、授受）**刻意不放在這裡**：這個集合只掛在初級，
 * 塞進去的話初級的人會在清單裡看到一半讀不懂的東西，而那正是會讓人放棄的畫面。
 *
 * 每課都刻意不帶文法術語當標題（不寫「五段動詞的ます形」），
 * 因為會被術語擋住的人正是這一階要救的人。
 */


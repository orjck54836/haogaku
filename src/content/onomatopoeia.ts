/**
 * オノマトペ（擬聲擬態語）。進階那一階的「語言系統」卡。
 *
 * ## 為什麼獨立出來，而不是只留生活主題裡那一個
 *
 * 生活主題的「擬聲擬態語」是**一個情境**（跟朋友聊美食和心情）。
 * 但擬聲擬態語不是情境，是日文的一整套詞彙系統：日本人形容痛、形容口感、
 * 形容心情幾乎都靠它，不會的話聽得懂每個助詞也還是接不上話。
 * 所以和敬語一樣拉出來，用分類整理（心情／身體／口感／聲音），
 * 而不是散在某一個場景裡。
 *
 * 兩個原本的入口都留著：這裡是「系統地學」，主題那邊是「在情境裡用」。
 *
 * ## 為什麼歸進階
 *
 * 擬聲擬態語本身的假名很簡單，難的是**它沒有中文對應**——
 * 「ふわふわ」不是「軟軟的」，是一種具體的輕盈感。初級的人還在把中文翻成日文，
 * 學這個會變成背一張對照表，用出來就不對。等到不靠翻譯也能講幾句之後再碰比較有用。
 *
 * ## 寫法的約束
 *
 * 一律標出**後面接什麼**（する／だ／と／直接當副詞），因為台灣學習者最常見的錯
 * 不是選錯詞，是詞選對了卻接錯——「ドキドキです」聽起來就不像日文。
 */


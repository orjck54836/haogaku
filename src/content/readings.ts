export const readingById = (id: string) => readings.find(r => r.id === id);

/**
 * 讀物也算進度，用這個 id 去對 progress.completed。
 * 前綴獨立出來，是為了讓「完成課程」那類統計能把讀物排除掉——
 * 讀物不是課，混在一起會讓數字看起來比實際多。
 */
const READING_PREFIX = 'read-';
export const readingLessonId = (id: string) => `${READING_PREFIX}${id}`;
export const isReadingLesson = (lessonId: string) => lessonId.startsWith(READING_PREFIX);

/** 每天換一篇當推薦。和流行語一樣用日期取餘數，同一天開 app 看到的都一樣 */
export function todayReadingIndex() {
  const d = new Date();
  const n = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  return n % readings.length;
}

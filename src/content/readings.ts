/**
 * 讀物。
 *
 * 全部是為這個 App 寫的原創短篇——不收青空文庫或任何現成作品。
 * 理由有兩個：授權乾淨，而且明治大正的文體對學習者太硬
 * （「〜のであつた」「候」這種形式現在沒人用，學了用不出去）。
 *
 * 寫作上的三條自我約束：
 * 1. **一行一個意思**。日文原文最長兩句，排版才讀得下去，點播放也剛好是一口氣。
 * 2. **只用現代口語會出現的句型**。文學性的倒裝和文語助動詞不用。
 * 3. **要有事情發生**。純寫景的散文學不到對話，每篇至少有一個場景或一句真的會說的話。
 *
 * level 是建議程度，不鎖——L3 的篇目 L1 的人也點得進去，只是漢字多一點。
 * photo 是 src/ui/images.ts 的 key，共用主題照片，不另外放圖。
 */

export type ReadingGenre = 'story' | 'essay' | 'culture';

/** 一行：日文原文配中譯。中譯寧可意譯順口，不要逐字對照 */

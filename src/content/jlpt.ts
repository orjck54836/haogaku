/** 題庫裡實際出現過的題型數。首頁的統計用，加了新題型自己會長 */
export const typeCount = new Set(jlptQuestions.map(q => q.type)).size;

/**
 * 「新」標記：三天內加的。不用「今天加的」——空中更新晚一天送到、或使用者隔天才打開，
 * 用「今天」比對的話那批內容一次都不會亮。
 */
export function isNewJlpt(added: string, today: string): boolean {
  const ms = Date.parse(today) - Date.parse(added);
  return ms >= 0 && ms < 3 * 86400000;
}

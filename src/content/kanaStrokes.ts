/**
 * 假名的筆畫骨架。
 *
 * **這不是字形**——畫在畫面上的字是內建明體（NotoSerifTC）渲染的，
 * 這裡的折線只當遮罩，決定「哪一段先出現」。一開始是拿它直接當字形畫，
 * 線條粗細均一、轉折也不對，看起來就是不像那個字。
 * 改成遮罩之後，座標只要落在字形的骨架上就夠，不用標得漂亮。
 *
 * 座標是 0〜100 的方格，y 往下，對齊的是明體在這個框裡的字面（約 10〜90）。
 * 渲染時用 Catmull-Rom 補成曲線，所以手標折線就夠。
 * 這個格式同時也是比對演算法要的格式（`src/lib/handwriting.ts` 直接重新取樣這些點）。
 *
 * 不引 KanjiVG：那份是 CC-BY-SA，衍生資料得同樣授權，
 * 跟這個專案（讀物全原創）的授權立場不一致。
 *
 * 平假名、片假名各 46 字全部齊了。補濁音／拗音時沿用同一個方格，不要改尺度——
 * 判定的容許距離是按 100 格調的。
 *
 * **骨架只標「手會怎麼動」，不要照著明體的輪廓描。**
 * 原本有二十幾個字把起筆的三角、收筆的尖尾也標進折線裡（「ち」的第一橫先往下再往上、
 * 「よ」的第一豎繞去右邊、「ね」的左豎中間凸一塊），這些轉折使用者根本不會畫，
 * 而 `judgeStroke` 是按「弧長等分後逐點比距離」，多出來的那一截會把整條線的對應位置推歪，
 * 結果是照著寫也永遠過不了。「ぬ」更嚴重：第二筆的起點標在右邊的小圈上，
 * 離真正的起筆 38 格，判定門檻是 34——怎麼寫都是「起筆的位置不對」。
 *
 * **座標要對著實際渲染的字形量，不要憑印象畫。** 遮罩是蓋在 NotoSerifTC 的字面上，
 * 骨架偏個五格就會蓋到隔壁那一筆、或露出沒蓋到的一截；「ね」「れ」「わ」的左豎
 * 本來標在 x=20，實際字形在 x=33，整條線都在空白處。校對方法是把同一個字用
 * NotoSerifTC_500Medium 以同樣的參數（fontSize 80、基線 y=80.4、置中）畫成圖，
 * 取中軸線（skeletonize）再把折線疊上去看。
 *
 * 畫數對過 eleschool-compass 的筆順表（字形來源 KanjiVG）。
 * 「き」4 畫、「さ」3 畫是教科書體的下半部分離寫法，印刷體看起來會連在一起。
 */

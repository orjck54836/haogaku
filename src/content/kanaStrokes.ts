/**
 * 假名的筆畫骨架。
 *
 * **這不是字形**——畫在畫面上的字是內建明體（NotoSerifTC）渲染的，
 * 這裡的折線只當遮罩，決定「哪一段先出現」。一開始是拿它直接當字形畫，
 * 線條粗細均一、轉折也不對，看起來就是不像那個字。
 * 改成遮罩之後，座標只要落在字形的骨架上就夠，不用標得漂亮。
 *
 * 座標是 0〜100 的方格，y 往下，對齊的是明體在這個框裡的字面（約 10〜90）。
 * 渲染時用 Catmull-Rom 補成曲線，所以手標折線就夠。
 * 這個格式同時也是比對演算法要的格式（`src/lib/handwriting.ts` 直接重新取樣這些點）。
 *
 * 不引 KanjiVG：那份是 CC-BY-SA，衍生資料得同樣授權，
 * 跟這個專案（讀物全原創）的授權立場不一致。
 *
 * 平假名、片假名各 46 字全部齊了。補濁音／拗音時沿用同一個方格，不要改尺度——
 * 判定的容許距離是按 100 格調的。
 *
 * 畫數對過 eleschool-compass 的筆順表（字形來源 KanjiVG）。
 * 「き」4 畫、「さ」3 畫是教科書體的下半部分離寫法，印刷體看起來會連在一起。
 */

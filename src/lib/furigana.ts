/**
 * 把寫在括號裡的注音拿掉。
 *
 * 產生出來的課文會寫成「週(しゅう)に3日(みっか)、入(はい)れます。」。這個寫法有兩個問題，
 * 而且兩個都只在畫面上看得出來：
 *
 * 1. **唸出來會重複。** TTS 把括號裡的假名當成另一個詞，「陳(ちん)さん」聽到的是
 *    「ちん ちん さん」。
 * 2. **括號貼的字和裡面的讀音對不起來。** 「3日(みっか)」的 みっか 是「3日」整個詞的讀音，
 *    但括號只貼在「日」後面；看起來就像在說「日 = みっか」。數字、送假名、複合詞
 *    都會發生，而且要判斷對不對需要詞法知識，規則修不乾淨。
 *
 * 所以畫面和語音都走同一個清理：**課文只留漢字**，讀音交給本來就有的那一行平假名
 * （LearnCard 的 `reading`）和朗讀。資料本身不動——之後重新產生課程時格式可能會變，
 * 清理放在讀出來的這一側才不會跟著資料版本綁死。
 *
 * 只處理「**漢字後面、括號裡全是假名**」的那一種，因為那才是注音。
 * 「(はい)」這種本身就是內容的括號、中文的括號註解（「（文法錯誤）」）都留著。
 *
 * **不要拿去清中文說明**（note／explain／hint）：那裡的括號是在補一個日文詞的原形，
 * 例如「切(きる)先,炒(いためる)後」，清掉會變成「切先,炒後」，整句就壞了。
 */
const FURIGANA = /([㐀-䶿一-鿿])[(（][぀-ゟ゠-ヿ ・ー]+[)）]/g;

export const stripFurigana = (text: string) => text.replace(FURIGANA, '$1');
